#!/usr/bin/env python3
"""Generate jglot's Java catalogs (token types, expression types, arg keys, data types) from sqlglot.

The generated files are committed; re-run this only when moving to a new sqlglot baseline:

    python tools/codegen/generate_catalog.py --sqlglot /path/to/sqlglot-checkout

Generated:
    tokens/TokenType.java          one constant per sqlglot TokenType, same order
    expressions/ExprType.java      one constant per sqlglot Expr subclass (traits included)
    expressions/ExprCatalog.java   per-type metadata: args, required flags, traits, SQL names
    expressions/Args.java          one Arg constant per distinct arg key
    expressions/DType.java         sqlglot's DataType.Type enum
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PKG = "io.github.offbyjuan.jglot"
HEADER = "// GENERATED by tools/codegen/generate_catalog.py from sqlglot {version}. Do not edit.\n"
CHUNK = 60


_WORD_BOUNDARY = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")


def const_name(cls_name: str) -> str:
    """JSONExtract -> JSON_EXTRACT, DPipe -> D_PIPE, MD5Digest -> MD5_DIGEST."""
    return _WORD_BOUNDARY.sub("_", cls_name).upper()


def jstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sqlglot", required=True)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[2] / "jglot/src/main/java"))
    args = ap.parse_args()
    sys.path.insert(0, str(Path(args.sqlglot).resolve()))

    import sqlglot.expressions as exp
    from sqlglot._version import __version__
    from sqlglot.tokens import TokenType

    out = Path(args.out) / PKG.replace(".", "/")
    header = HEADER.format(version=__version__)

    # ---------------------------------------------------------------- TokenType
    lines = [header, f"package {PKG}.tokens;\n", "/** sqlglot token types, in sqlglot's declaration order. */",
             "public enum TokenType {"]
    token_names = [t.name for t in TokenType]
    lines.append(",\n".join(f"    {n}" for n in token_names) + ";")
    lines.append("}")
    (out / "tokens").mkdir(parents=True, exist_ok=True)
    (out / "expressions").mkdir(parents=True, exist_ok=True)
    (out / "tokens/TokenType.java").write_text("\n".join(lines) + "\n")

    # ---------------------------------------------------------------- DType
    dtype_names = [d.name for d in exp.DType]
    lines = [header, f"package {PKG}.expressions;\n",
             "/** sqlglot's {@code DataType.Type}: the canonical data type kinds. */",
             "public enum DType {"]
    lines.append(",\n".join(f"    {n}" for n in dtype_names) + ";")
    lines.append("}")
    (out / "expressions/DType.java").write_text("\n".join(lines) + "\n")

    # ---------------------------------------------------------------- Expr types
    classes = sorted(exp.EXPR_CLASSES.values(), key=lambda c: c.key)
    by_cls = {c: i for i, c in enumerate(classes)}
    consts = {}
    for c in classes:
        n = const_name(c.__name__)
        if n in consts.values():
            raise SystemExit(f"constant name collision: {n}")
        consts[c] = n

    arg_keys: dict[str, None] = {}
    for c in classes:
        for k in c.arg_types:
            arg_keys.setdefault(k, None)
    arg_names = sorted(arg_keys)

    def is_trait(c) -> bool:
        return not issubclass(c, exp.Expression)

    lines = [header, f"package {PKG}.expressions;\n",
             "/**",
             " * Every sqlglot expression type, including the abstract traits ({@code FUNC}, {@code BINARY},",
             " * {@code CONDITION}, ...). Metadata (args, traits, SQL names) is attached by {@link ExprCatalog}.",
             " */",
             "public enum ExprType {"]
    lines.append(",\n".join(f"    {consts[c]}" for c in classes) + ";")
    lines.append("""
    String key;
    String className;
    Arg[] args;
    boolean[] required;
    long[] ancestors;
    boolean trait;
    boolean varLenArgs;
    Arg varLenArgKey;
    int flags;
    String[] sqlNames;

    static final int F_SUBQUERY = 1, F_CAST = 2, F_DATA_TYPE = 4, F_PRIMITIVE = 8, F_HASH_RAW_ARGS = 16;

    static {
        ExprCatalog.init();
    }

    /** sqlglot's lowercase class key, e.g. {@code "select"}. */
    public String key() {
        return key;
    }

    /** sqlglot's class name, e.g. {@code "Select"}. */
    public String className() {
        return className;
    }

    /** The arg keys this type accepts, in sqlglot's declaration order. */
    public Arg[] args() {
        return args.clone();
    }

    public int argCount() {
        return args.length;
    }

    public Arg argAt(int slot) {
        return args[slot];
    }

    public boolean isRequired(int slot) {
        return required[slot];
    }

    /** The slot index of {@code arg}, or -1 if this type does not accept it. */
    public int slot(Arg arg) {
        Arg[] a = args;
        for (int i = 0; i < a.length; i++) {
            if (a[i] == arg) {
                return i;
            }
        }
        return -1;
    }

    /** Whether this type is {@code other} or inherits from it (sqlglot {@code issubclass}). */
    public boolean isA(ExprType other) {
        int o = other.ordinal();
        return (ancestors[o >>> 6] & (1L << o)) != 0;
    }

    /** Whether this is an abstract trait such as {@code FUNC} rather than a concrete node type. */
    public boolean isTrait() {
        return trait;
    }

    public boolean isVarLenArgs() {
        return varLenArgs;
    }

    public Arg varLenArgKey() {
        return varLenArgKey;
    }

    public boolean isSubqueryType() {
        return (flags & F_SUBQUERY) != 0;
    }

    public boolean isCastType() {
        return (flags & F_CAST) != 0;
    }

    public boolean isDataTypeType() {
        return (flags & F_DATA_TYPE) != 0;
    }

    public boolean isPrimitive() {
        return (flags & F_PRIMITIVE) != 0;
    }

    public boolean hashRawArgs() {
        return (flags & F_HASH_RAW_ARGS) != 0;
    }

    /** For function types: the SQL name (first) and aliases. Empty for non-functions. */
    public String[] sqlNames() {
        return sqlNames.clone();
    }

    /** For function types: the canonical SQL name. */
    public String sqlName() {
        if (sqlNames.length == 0) {
            throw new IllegalStateException(this + " is not a function type");
        }
        return sqlNames[0];
    }
}""")
    (out / "expressions/ExprType.java").write_text("\n".join(lines) + "\n")

    # ---------------------------------------------------------------- Args
    lines = [header, f"package {PKG}.expressions;\n",
             "/** One {@link Arg} constant per distinct sqlglot arg key. */",
             "public final class Args {",
             "    private Args() {}\n"]
    for i, k in enumerate(arg_names):
        lines.append(f"    public static final Arg {k.upper()} = Arg.register({jstr(k)}, {i});")
    lines.append(f"\n    static final int ARG_KEY_COUNT = {len(arg_names)};")
    lines.append("}")
    (out / "expressions/Args.java").write_text("\n".join(lines) + "\n")

    # ---------------------------------------------------------------- Catalog
    words = (len(classes) + 63) // 64
    lines = [header, f"package {PKG}.expressions;\n",
             "import static io.github.offbyjuan.jglot.expressions.ExprType.*;\n",
             "final class ExprCatalog {",
             "    private ExprCatalog() {}\n",
             "    private static final Arg[] NO_ARGS = {};",
             "    private static final boolean[] NO_REQ = {};",
             "    private static final String[] NO_NAMES = {};\n",
             "    private static void def(ExprType t, String className, String key, boolean trait, int flags,",
             "            boolean varLen, Arg varLenKey, Arg[] args, boolean[] required, String[] sqlNames, ExprType... parents) {",
             "        t.className = className;",
             "        t.key = key;",
             "        t.trait = trait;",
             "        t.flags = flags;",
             "        t.varLenArgs = varLen;",
             "        t.varLenArgKey = varLenKey;",
             "        t.args = args;",
             "        t.required = required;",
             "        t.sqlNames = sqlNames;",
             f"        long[] anc = new long[{words}];",
             "        anc[t.ordinal() >>> 6] |= 1L << t.ordinal();",
             "        for (ExprType p : parents) {",
             "            anc[p.ordinal() >>> 6] |= 1L << p.ordinal();",
             "        }",
             "        t.ancestors = anc;",
             "    }\n"]
    chunks = [classes[i:i + CHUNK] for i in range(0, len(classes), CHUNK)]
    lines.append("    static void init() {")
    for i in range(len(chunks)):
        lines.append(f"        init{i}();")
    lines.append("    }\n")
    for i, chunk in enumerate(chunks):
        lines.append(f"    private static void init{i}() {{")
        for c in chunk:
            flags = []
            if getattr(c, "is_subquery", False):
                flags.append("SUBQUERY")
            if getattr(c, "is_cast", False):
                flags.append("CAST")
            if getattr(c, "is_data_type", False):
                flags.append("DATA_TYPE")
            if getattr(c, "is_primitive", False):
                flags.append("PRIMITIVE")
            if getattr(c, "_hash_raw_args", False):
                flags.append("HASH_RAW_ARGS")
            flag_expr = " | ".join(f"ExprType.F_{f}" for f in flags) or "0"
            keys = list(c.arg_types)
            args_expr = ("new Arg[] {" + ", ".join(f"Args.{k.upper()}" for k in keys) + "}") if keys else "NO_ARGS"
            req_expr = ("new boolean[] {" + ", ".join("true" if c.arg_types[k] else "false" for k in keys) + "}") if keys else "NO_REQ"
            names = []
            if issubclass(c, exp.Func) and c is not exp.Func and not is_trait(c):
                names = c.sql_names()
            names_expr = ("new String[] {" + ", ".join(jstr(n) for n in names) + "}") if names else "NO_NAMES"
            var_len = bool(getattr(c, "is_var_len_args", False))
            vkey = getattr(c, "var_len_arg_key", "expressions")
            vkey_expr = f"Args.{vkey.upper()}" if var_len and vkey in arg_keys else "null"
            parents = [p for p in c.__mro__[1:] if isinstance(p, type) and issubclass(p, exp.Expr) and p in by_cls]
            parent_expr = "".join(f", {consts[p]}" for p in parents)
            lines.append(
                f"        def({consts[c]}, {jstr(c.__name__)}, {jstr(c.key)}, {'true' if is_trait(c) else 'false'}, "
                f"{flag_expr}, {'true' if var_len else 'false'}, {vkey_expr}, {args_expr}, {req_expr}, {names_expr}{parent_expr});")
        lines.append("    }\n")
    lines.append("}")
    (out / "expressions/ExprCatalog.java").write_text("\n".join(lines) + "\n")

    print(f"sqlglot {__version__}: {len(token_names)} token types, {len(classes)} expression types, "
          f"{len(arg_names)} arg keys, {len(dtype_names)} data types", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
