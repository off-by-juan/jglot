def tokenizer_method(dialect_cls, key: str) -> list[str]:
    tok = dialect_cls.tokenizer_class
    d = dialect_cls
    L = [f"    static TokenizerConfig {method_name(key)}() {{",
         "        TokenizerConfig.Builder b = TokenizerConfig.builder();"]
    for c, t in sorted(tok.SINGLE_TOKENS.items()):
        L.append(f"        b.single({jchar(c)}, TokenType.{t.name});")
    for k, t in sorted(tok.KEYWORDS.items()):
        L.append(f"        b.kw({jstr(k)}, TokenType.{t.name});")
    for s, e in tok._QUOTES.items():
        L.append(f"        b.quotes.put({jstr(s)}, {jstr(e)});")
    for s, (e, t) in tok._FORMAT_STRINGS.items():
        L.append(f"        b.format({jstr(s)}, {jstr(e)}, TokenType.{t.name});")
    for s, e in tok._IDENTIFIERS.items():
        if len(s) != 1:
            continue  # multi-char identifier starts can never match a single scanned char
        L.append(f"        b.identifiers.put({jchar(s)}, {jstr(e)});")
    for s, e in tok._COMMENTS.items():
        L.append(f"        b.comments.put({jstr(s)}, {jstr(e) if e else 'null'});")
    for name, attr in (("stringEscapes", "_STRING_ESCAPES"), ("byteStringEscapes", "_BYTE_STRING_ESCAPES"),
                       ("identifierEscapes", "_IDENTIFIER_ESCAPES")):
        for c in sorted(getattr(tok, attr)):
            L.append(f"        b.{name}.add({jchar(c)});")
    for c in tok.STRING_ESCAPES:
        L.append(f"        b.stringEscapesOrdered.add({jstr(c)});")
    for t in sorted(tok.COMMANDS, key=lambda x: x.name):
        L.append(f"        b.commands.add(TokenType.{t.name});")
    for t in sorted(tok.COMMAND_PREFIX_TOKENS, key=lambda x: x.name):
        L.append(f"        b.commandPrefixTokens.add(TokenType.{t.name});")
    for t in sorted(tok.TOKENS_PRECEDING_HINT, key=lambda x: x.name):
        L.append(f"        b.tokensPrecedingHint.add(TokenType.{t.name});")
    for k, v in sorted(tok.NUMERIC_LITERALS.items()):
        L.append(f"        b.numericLiterals.put({jstr(k)}, {jstr(v)});")
    for c in sorted(tok.VAR_SINGLE_TOKENS):
        L.append(f"        b.varSingleTokens.add({jchar(c)});")
    for k, v in sorted(d.UNESCAPED_SEQUENCES.items()):
        L.append(f"        b.unescapedSequences.put({jstr(k)}, {jstr(v)});")
    for k, v in sorted(tok.NUMERIC_ESCAPES.items()):
        L.append(f"        b.numericEscapes.put({jchar(k)}, new int[] {{{', '.join(str(x) for x in v)}}});")

    trie_keys = [
        key.upper()
        for key in (*tok.KEYWORDS, *tok._COMMENTS, *tok._QUOTES, *tok._FORMAT_STRINGS)
        if " " in key or any(single in key for single in tok.SINGLE_TOKENS)
    ]
    for k in sorted(set(trie_keys)):
        L.append(f"        b.keywordTrieKeys.add({jstr(k)});")

    def b(v):
        return "true" if v else "false"

    L += [
        f"        b.nestedComments = {b(tok.NESTED_COMMENTS)};",
        f"        b.dashCommentRequiresBoundary = {b(tok.DASH_COMMENT_REQUIRES_BOUNDARY)};",
        f"        b.commentsTerminateAtNewlineOnly = {b(tok.COMMENTS_TERMINATE_AT_NEWLINE_ONLY)};",
        f"        b.hintStart = {jstr(tok.HINT_START)};",
        f"        b.hasBitStrings = {b(tok.BIT_STRINGS)};",
        f"        b.hasHexStrings = {b(tok.HEX_STRINGS)};",
        f"        b.stringEscapesAllowedInRawStrings = {b(tok.STRING_ESCAPES_ALLOWED_IN_RAW_STRINGS)};",
        f"        b.heredocTagIsIdentifier = {b(tok.HEREDOC_TAG_IS_IDENTIFIER)};",
        f"        b.heredocStringAlternative = TokenType.{tok.HEREDOC_STRING_ALTERNATIVE.name};",
        f"        b.numbersCanBeUnderscoreSeparated = {b(d.NUMBERS_CAN_BE_UNDERSCORE_SEPARATED)};",
        f"        b.numbersCanHaveDecimals = {b(tok.NUMBERS_CAN_HAVE_DECIMALS)};",
        f"        b.identifiersCanStartWithDigit = {b(d.IDENTIFIERS_CAN_START_WITH_DIGIT)};",
        f"        b.dropUnknownEscapes = {b(tok.DROP_UNKNOWN_ESCAPES)};",
        f"        b.numericEscapesAreBytes = {b(tok.NUMERIC_ESCAPES_ARE_BYTES)};",
        f"        b.byteStringsAreBytes = {b(d.BYTE_STRING_IS_BYTES_TYPE)};",
        f"        b.loneSurrogateReplacement = {jstr(tok.LONE_SURROGATE_REPLACEMENT)};",
        "        return b.build();",
        "    }",
        "",
    ]
    return L


