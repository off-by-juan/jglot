def jstr(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 32 or o > 126:
            if o > 0xFFFF:
                hi, lo = divmod(o - 0x10000, 0x400)
                out.append(f"\\u{0xD800 + hi:04x}\\u{0xDC00 + lo:04x}")
            else:
                out.append(f"\\u{o:04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def jchar(c: str) -> str:
    assert len(c) == 1, c
    if c == "'":
        return "'\\''"
    if c == "\\":
        return "'\\\\'"
    return "'" + jstr(c)[1:-1] + "'"


def method_name(key: str) -> str:
    return key or "base"


