class Ctx:
    def __init__(self, exp, TokenType, DType, const_names, PropertiesLocation):
        self.exp = exp
        self.TokenType = TokenType
        self.DType = DType
        self.const_names = const_names
        self.PL = PropertiesLocation

    def exptype(self, cls) -> str:
        return "ExprType." + self.const_names[cls]


def is_exp_cls(ctx, x) -> bool:
    return isinstance(x, type) and issubclass(x, ctx.exp.Expr)


def classify(ctx, v) -> str | None:
    """Returns a Java type for value v, or None if it can't be represented / is empty-ambiguous."""
    exp, TokenType, DType = ctx.exp, ctx.TokenType, ctx.DType
    if isinstance(v, bool):
        return "boolean"
    if isinstance(v, int):
        return "int"
    if isinstance(v, str):
        return "String"
    if v is None:
        return None
    if isinstance(v, ctx.PL):
        return "PropertiesLocation"
    if isinstance(v, DType):
        return "DType"
    if isinstance(v, re.Pattern):
        return "Pattern"
    if isinstance(v, exp.Expr):
        return "Template"
    if isinstance(v, (set, frozenset)):
        if not v:
            return None
        x = next(iter(v))
        if isinstance(x, TokenType):
            return "Set<TokenType>"
        if isinstance(x, DType):
            return "Set<DType>"
        if isinstance(x, str):
            return "Set<String>"
        if is_exp_cls(ctx, x):
            return "Set<ExprType>"
        return "?set"
    if isinstance(v, (tuple, list)):
        if not v:
            return None
        x = v[0]
        if isinstance(x, TokenType):
            return "Set<TokenType>"
        if isinstance(x, str):
            return "List<String>"
        if is_exp_cls(ctx, x):
            return "List<ExprType>"
        return "?tuple"
    if isinstance(v, dict):
        if not v:
            return None
        k = next(iter(v))
        val = next(iter(v.values()))
        vals = list(v.values())
        if any(callable(x) and not isinstance(x, type) for x in vals) or (
            any(x is None for x in vals) and any(callable(x) for x in vals)
        ):
            if isinstance(k, TokenType):
                return "Keys<TokenType>"
            if isinstance(k, str):
                return "Keys<String>"
            if is_exp_cls(ctx, k):
                return "Keys<ExprType>"
            if isinstance(k, DType):
                return "Keys<DType>"
            return "?keys"
        if isinstance(k, TokenType) and is_exp_cls(ctx, val):
            return "Map<TokenType,ExprType>"
        if isinstance(k, TokenType) and isinstance(val, TokenType):
            return "Map<TokenType,TokenType>"
        if isinstance(k, TokenType) and isinstance(val, str):
            return "Map<TokenType,String>"
        if isinstance(k, str) and is_exp_cls(ctx, val):
            return "Map<String,ExprType>"
        if isinstance(k, str) and isinstance(val, str):
            return "Map<String,String>"
        if isinstance(k, str) and isinstance(val, tuple):
            return "Options"
        if isinstance(k, tuple) and isinstance(val, str):
            return "Map<List<String>,String>"
        if isinstance(k, DType) and isinstance(val, str):
            return "Map<DType,String>"
        if is_exp_cls(ctx, k) and isinstance(val, ctx.PL):
            return "Map<ExprType,PropertiesLocation>"
        if is_exp_cls(ctx, k) and isinstance(val, (bool, type(None))):
            return "Map<ExprType,Boolean>"
        if isinstance(k, DType) and isinstance(val, tuple):
            return "Map<DType,List<String>>"
        return "?dict"
    if callable(v):
        return None
    return "?" + type(v).__name__


JAVA_FIELD_TYPE = {
    "Keys<TokenType>": "Set<TokenType>",
    "Keys<String>": "Set<String>",
    "Keys<ExprType>": "Set<ExprType>",
    "Keys<DType>": "Set<DType>",
    "Options": "Map<String, List<List<String>>>",
    "Template": "String",
    "Pattern": "String",
}


def field_type(t: str) -> str:
    return JAVA_FIELD_TYPE.get(t, t.replace(",", ", "))


def default_value(t: str) -> str:
    if t == "boolean":
        return "false"
    if t == "int":
        return "0"
    ft = field_type(t)
    if ft.startswith("Set<"):
        return "Set.of()"
    if ft.startswith("Map<"):
        return "Map.of()"
    if ft.startswith("List<"):
        return "List.of()"
    return "null"


def emit_value(ctx, t: str, v) -> str:
    """Java expression for value v of declared type t."""
    exp, TokenType, DType = ctx.exp, ctx.TokenType, ctx.DType

    def tt(x):
        return f"TokenType.{x.name}"

    def dt(x):
        return f"DType.{x.name}"

    if v is None:
        return default_value(t)
    if t == "boolean":
        return "true" if v else "false"
    if t == "Boolean":
        return "Boolean.TRUE" if v else "Boolean.FALSE"
    if t == "int":
        return str(v)
    if t == "String":
        return jstr(v)
    if t == "Object":
        return ("Boolean.TRUE" if v else "Boolean.FALSE") if isinstance(v, bool) else jstr(v)
    if t == "PropertiesLocation":
        return f"PropertiesLocation.{v.name}"
    if t == "DType":
        return dt(v)
    if t == "Pattern":
        return jstr(v.pattern)
    if t == "Template":
        return jstr(v.sql())
    ft = field_type(t)
    if ft == "Set<TokenType>":
        items = sorted(v, key=lambda x: x.name)
        return "tokens(" + ", ".join(tt(x) for x in items) + ")"
    if ft == "Set<DType>":
        items = sorted(v, key=lambda x: x.name)
        return "dtypes(" + ", ".join(dt(x) for x in items) + ")"
    if ft == "Set<String>":
        return "strings(" + ", ".join(jstr(x) for x in sorted(v)) + ")"
    if ft == "Set<ExprType>":
        items = sorted(v, key=lambda x: ctx.const_names[x])
        return "types(" + ", ".join(ctx.exptype(x) for x in items) + ")"
    if ft == "List<String>":
        return "List.of(" + ", ".join(jstr(x) for x in v) + ")"
    if ft == "List<ExprType>":
        return "List.of(" + ", ".join(ctx.exptype(x) for x in v) + ")"
    if t == "Map<TokenType,ExprType>":
        return "map(" + ", ".join(f"{tt(k)}, {ctx.exptype(x)}" for k, x in sorted(v.items(), key=lambda kv: kv[0].name)) + ")"
    if t == "Map<TokenType,TokenType>":
        return "map(" + ", ".join(f"{tt(k)}, {tt(x)}" for k, x in sorted(v.items(), key=lambda kv: kv[0].name)) + ")"
    if t == "Map<TokenType,String>":
        return "map(" + ", ".join(f"{tt(k)}, {jstr(x)}" for k, x in sorted(v.items(), key=lambda kv: kv[0].name)) + ")"
    if t == "Map<String,ExprType>":
        return "map(" + ", ".join(f"{jstr(k)}, {ctx.exptype(x)}" for k, x in sorted(v.items())) + ")"
    if t == "Map<String,String>":
        return "map(" + ", ".join(f"{jstr(k)}, {jstr(x)}" for k, x in v.items()) + ")"
    if t == "Map<String,List<String>>":
        return "map(" + ", ".join(f"{jstr(k)}, List.of({', '.join(jstr(str(e)) for e in x)})" for k, x in v.items()) + ")"
    if t == "Map<DType,List<String>>":
        return "map(" + ", ".join(f"{dt(k)}, List.of({', '.join(jstr(str(e)) for e in x)})" for k, x in v.items()) + ")"
    if t == "Map<DType,String>":
        return "map(" + ", ".join(f"{dt(k)}, {jstr(x)}" for k, x in sorted(v.items(), key=lambda kv: kv[0].name)) + ")"
    if t == "Map<List<String>,String>":
        return "map(" + ", ".join(f"List.of({', '.join(jstr(e) for e in k)}), {jstr(x)}" for k, x in v.items()) + ")"
    if t == "Map<ExprType,PropertiesLocation>":
        return "map(" + ", ".join(f"{ctx.exptype(k)}, PropertiesLocation.{x.name}" for k, x in sorted(v.items(), key=lambda kv: ctx.const_names[kv[0]])) + ")"
    if t == "Map<ExprType,Boolean>":
        return "map(" + ", ".join(f"{ctx.exptype(k)}, {'null' if x is None else ('Boolean.TRUE' if x else 'Boolean.FALSE')}" for k, x in v.items()) + ")"
    if t == "Options":
        parts = []
        for k, conts in v.items():
            seqs = []
            for c in conts:
                words = (c,) if isinstance(c, str) else tuple(c)
                seqs.append("List.of(" + ", ".join(jstr(w) for w in words) + ")")
            parts.append(f"{jstr(k)}, List.of({', '.join(seqs)})")
        return "options(" + ", ".join(parts) + ")"
    if t.startswith("Keys<"):
        keys = list(v.keys())
        if t == "Keys<TokenType>":
            return "tokens(" + ", ".join(tt(x) for x in sorted(keys, key=lambda x: x.name)) + ")"
        if t == "Keys<String>":
            return "strings(" + ", ".join(jstr(x) for x in sorted(keys)) + ")"
        if t == "Keys<ExprType>":
            return "types(" + ", ".join(ctx.exptype(x) for x in sorted(keys, key=lambda x: ctx.const_names[x])) + ")"
        if t == "Keys<DType>":
            return "dtypes(" + ", ".join(dt(x) for x in sorted(keys, key=lambda x: x.name)) + ")"
    raise ValueError(f"cannot emit {t}: {v!r}")


def collect_types(ctx, classes_by_dialect, extra_overrides=None) -> dict[str, str]:
    """attribute -> declared type, unified across all dialect classes."""
    seen: dict[str, set[str]] = {}
    for cls in classes_by_dialect:
        for a in dir(cls):
            if a.startswith("_") or a.upper() != a or a in SKIP:
                continue
            v = getattr(cls, a)
            t = classify(ctx, v)
            seen.setdefault(a, set())
            if t is not None:
                seen[a].add(t)
    out = {}
    for a, ts in seen.items():
        ov = (extra_overrides or {}).get(a) or OVERRIDES.get(a)
        if ov:
            out[a] = ov
            continue
        if "boolean" in ts and len(ts) == 1:
            out[a] = "boolean"
        elif not ts:
            out[a] = "Set<String>"
        elif len(ts) == 1:
            t = next(iter(ts))
            if t.startswith("?"):
                print(f"warning: skipping {a}: {t}", file=sys.stderr)
                continue
            out[a] = t
        else:
            print(f"warning: skipping {a}: ambiguous types {ts}", file=sys.stderr)
    return out


def chunked(lines, n=250):
    for i in range(0, len(lines), n):
        yield lines[i:i + n]


