#!/usr/bin/env python3
"""Generate fully-resolved per-dialect data tables from sqlglot.

sqlglot dialects inherit and override large tables of plain data: tokenizer keywords and quote
characters, parser token sets and flags, generator flags and type mappings, dialect settings. Rather
than hand-copying them, this script resolves each dialect's values in sqlglot and emits them as Java,
so the Java port only hand-writes behaviour.

Callable tables (e.g. Parser.STATEMENT_PARSERS) are emitted as key sets: the Java parser dispatches
on the key with an overridable method, and the key set tells it which keys the dialect has. Where a
callable is a known factory with plain-data arguments, it is emitted as data instead:

    Parser.FUNCTIONS          FUNCTIONS_FROM_ARG_LIST (name -> ExprType) + FUNCTIONS_CUSTOM keys
    Generator.TRANSFORMS      TRANSFORMS_RENAME (ExprType -> SQL name) + TRANSFORMS_CUSTOM keys

    python tools/codegen/generate_dialect_data.py --sqlglot /path/to/sqlglot-checkout

Generated (in jglot/src/main/java/io/github/offbyjuan/jglot/dialects/data/):
    TokenizerData.java, ParserData.java, GeneratorData.java, DialectData.java, PropertiesLocation.java
"""

