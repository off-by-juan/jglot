#!/usr/bin/env python3
"""Build a differential corpus: sqlglot's own SQL fixture files transpiled into every jglot dialect.

sqlglot's dialect tests (extract_sqlglot_fixtures.py) cover what sqlglot's authors chose to assert.
This adds breadth: every statement in sqlglot's identity.sql, pretty.sql and optimizer fixture
files (including TPC-H and TPC-DS), read in its declared dialect, is generated by sqlglot into each
jglot dialect, plain and pretty. sqlglot's output is the expected value, and whether
unsupported_level=RAISE raises is recorded, so jglot can be checked for exact parity, including
the fail-loudly behaviour.

    python tools/fixtures/extract_differential_fixtures.py --sqlglot /path/to/sqlglot \
        --out jglot/src/test/resources/fixtures/differential/cases.json.gz
"""

from __future__ import annotations

import argparse
import gzip
import json
import logging
import sys
from pathlib import Path

DIALECTS = ["", "postgres", "presto", "trino", "bigquery", "clickhouse", "hive"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sqlglot", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    root = Path(args.sqlglot).resolve()
    sys.path.insert(0, str(root))
    logging.disable(logging.CRITICAL)

    from sqlglot import ErrorLevel, UnsupportedError, parse_one
    from sqlglot._version import __version__
    from tests.helpers import load_sql_fixture_pairs, load_sql_fixtures

    sources: list[tuple[str, str, str]] = []  # (origin, read dialect, sql)
    for line in load_sql_fixtures("identity.sql"):
        if line.strip():
            sources.append(("identity.sql", "", line))
    for _, sql, _pretty in load_sql_fixture_pairs("pretty.sql"):
        sources.append(("pretty.sql", "", sql))
    opt = root / "tests/fixtures/optimizer"
    files = sorted(p.relative_to(root / "tests/fixtures") for p in opt.rglob("*.sql"))
    for rel in files:
        for meta, sql, expected in load_sql_fixture_pairs(str(rel)):
            dialect = meta.get("dialect", "")
            if dialect not in DIALECTS:
                continue
            for s in (sql, expected):
                if s:
                    sources.append((str(rel), dialect, s))

    seen = set()
    cases = []
    stats = {"sources": 0, "parse_errors": 0, "cases": 0}
    for origin, read, sql in sources:
        if (read, sql) in seen:
            continue
        seen.add((read, sql))
        try:
            tree = parse_one(sql, read=read)
        except Exception:
            stats["parse_errors"] += 1
            continue
        if tree is None:
            continue
        stats["sources"] += 1
        outputs = {}
        for write in DIALECTS:
            entry = {}
            for pretty in (False, True):
                try:
                    out = tree.sql(dialect=write, pretty=pretty, unsupported_level=ErrorLevel.IGNORE)
                except Exception as e:  # sqlglot itself fails: record, jglot should fail too
                    out = None
                    entry["generateError"] = type(e).__name__
                entry["pretty" if pretty else "sql"] = out
            try:
                tree.sql(dialect=write, unsupported_level=ErrorLevel.RAISE)
                entry["raises"] = False
            except UnsupportedError:
                entry["raises"] = True
            except Exception:
                entry["raises"] = None
            outputs[write] = entry
            stats["cases"] += 1
        cases.append({"origin": origin, "read": read, "sql": sql, "outputs": outputs})

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(out, "wt", encoding="utf-8") as fh:
        json.dump({"sqlglotVersion": __version__, "dialects": DIALECTS, "cases": cases}, fh, ensure_ascii=False)
    print(f"sqlglot {__version__}: {stats}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
